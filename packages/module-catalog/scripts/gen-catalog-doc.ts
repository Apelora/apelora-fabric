import { writeFileSync } from "node:fs";
import { CATEGORIES } from "@apelora/assembly-model";
import { MODULE_CLASSES } from "../src/classes";
import { catalogImagesJson } from "../src/images";

type Class = (typeof MODULE_CLASSES)[number];
const by = (cat: string) => MODULE_CLASSES.filter((c) => c.category === cat);
const fmt = (c: Class, dir: "input" | "output") =>
  c.ports.filter((p) => p.direction === dir).map((p) => `\`${p.name}\` ${p.type}${dir === "input" && !p.optional ? "*" : ""}${p.multiplicity === "one" ? " (1)" : ""}`).join(", ") || "—";

const SOURCE = { native: "built in", exporter: "exporter", agent: "agent (optional)", platform: "Incus", none: "none" } as const;
/** Metrics column: source, port and path, the format when it is not metrics text, and whether it is off or unverified. */
const metrics = (c: Class) => {
  const m = c.metrics;
  if (!m) return "—";
  const ports = m.portBy ? [...new Set([m.port, ...Object.values(m.portBy.ports)])].join("/") : m.port;
  const port = m.port === undefined ? "" : ` · ${m.transport === "udp" ? "udp/" : ""}${ports}${m.portChosen ? " (set)" : ""}`;
  const path = m.path ? ` \`${m.path}\`` : "";
  const format = m.format === "text" || m.format === "none" ? "" : ` (${m.format})`;
  const state = [m.source !== "none" && !m.onByDefault ? "off by default" : "", m.localOnly ? "localhost by default" : "", m.confidence === "unverified" ? "**unverified**" : ""].filter(Boolean);
  return `${SOURCE[m.source]}${port}${path}${format}${state.length ? `, ${state.join(", ")}` : ""}`;
};

let md = `# Module catalog reference

Generated by \`npm run catalog:doc\` from \`packages/module-catalog/src\`. Do not edit by hand.

${MODULE_CLASSES.length} modules in ${CATEGORIES.filter((c) => by(c).length).length} categories. \`*\` = required, \`(1)\` = single cable. Every module also has a \`net\` input (NIC) as its last left-hand terminal.

**Metrics** says where the software's own metrics come from (built in, a separate exporter, an optional agent in the guest, Incus, or none), then the port and path, the format when it is not metrics text, and whether they are off or reachable only on localhost by default. "(set)" marks a port the class chooses because the software has no default. A class whose metrics a collector reads as text on a port has a \`mon\` output, and a drawn \`mon\` connection opens exactly that port ([MODULE-PORTS.md](MODULE-PORTS.md#metrics-the-mon-output)). How to turn each one on, the signals worth watching and how well the facts were checked are in \`packages/module-catalog/src/metrics.ts\` and in the Studio inspector.

`;
for (const cat of CATEGORIES) {
  const list = by(cat);
  if (!list.length) continue;
  md += `## ${cat}\n\n| Module | Inputs (left) | Outputs (right) | vCPU / MiB | Metrics | Settings |\n|---|---|---|---|---|---|\n`;
  for (const c of list) md += `| **${c.displayName}** (\`${c.id}\`) | ${fmt(c, "input")} | ${fmt(c, "output")} | ${c.resources.cpu} / ${c.resources.memoryMiB} | ${metrics(c)} | ${(c.properties ?? []).map((p) => p.label).join(", ") || "—"} |\n`;
  md += "\n";
}
const deployable = MODULE_CLASSES.filter((c) => c.runtime);
md += `## Deployable modules

${deployable.length} of ${MODULE_CLASSES.length} classes have an Incus runtime; the others are design-only. A runtime is added only after its images have run on the disposable test cluster. The runtime decides the instance kind: a system container unless the class needs an OCI application container or a virtual machine ([how a module becomes instances](PLATFORM-ARCHITECTURE.md#41-from-an-application-to-running-instances)).

| Module | Runtime | Image by setting |
|---|---|---|
`;
const KIND: Record<NonNullable<(typeof deployable)[number]["runtime"]>["kind"], string> = {
  "incus-system-container": "system container",
  "incus-oci-container": "OCI application container",
  "incus-vm": "virtual machine",
};
for (const c of deployable) {
  const rt = c.runtime!;
  const show = (img: NonNullable<typeof rt.image>) => ("reference" in img ? `\`${img.reference.replace(/@sha256:(.{12}).*/, "@sha256:$1…")}\`${img.version ? ` (${img.version})` : ""}` : `\`${img.alias}\``);
  const images = rt.image
    ? show(rt.image)
    : Object.entries(rt.imageBy!.images).map(([k, v]) => `${rt.imageBy!.property} = ${k}: ${show(v)}`).join("<br>");
  md += `| **${c.displayName}** (\`${c.id}\`) | ${KIND[rt.kind]} (\`${rt.kind}\`) | ${images} |\n`;
}
md += "\n";
writeFileSync(new URL("../../../docs/architecture/CATALOG.md", import.meta.url), md);
console.log(`catalog doc written (${MODULE_CLASSES.length} modules)`);
// The images the deployable classes use, for the control plane's image-mirror check (ADR 0010).
writeFileSync(new URL("../catalog-images.json", import.meta.url), catalogImagesJson());
console.log("catalog-images.json written");
