import { writeFileSync } from "node:fs";
import { CATEGORIES } from "@apelora/assembly-model";
import { APPLIANCE_CLASSES } from "../src/classes";

const by = (cat: string) => APPLIANCE_CLASSES.filter((c) => c.category === cat);
const fmt = (c: (typeof APPLIANCE_CLASSES)[number], dir: "input" | "output") =>
  c.ports.filter((p) => p.direction === dir).map((p) => `\`${p.name}\` ${p.type}${dir === "input" && !p.optional ? "*" : ""}${p.multiplicity === "one" ? " (1)" : ""}`).join(", ") || "—";

let md = `# Appliance catalog reference

Generated by \`npm run catalog:doc\` from \`packages/appliance-catalog/src\`. Do not edit by hand.

${APPLIANCE_CLASSES.length} appliances in ${CATEGORIES.filter((c) => by(c).length).length} categories. \`*\` = required, \`(1)\` = single cable. Every appliance also has a \`net\` input (NIC) as its last left-hand terminal.

`;
for (const cat of CATEGORIES) {
  const list = by(cat);
  if (!list.length) continue;
  md += `## ${cat}\n\n| Appliance | Inputs (left) | Outputs (right) | vCPU / MiB | Settings |\n|---|---|---|---|---|\n`;
  for (const c of list) md += `| **${c.displayName}** (\`${c.id}\`) | ${fmt(c, "input")} | ${fmt(c, "output")} | ${c.resources.cpu} / ${c.resources.memoryMiB} | ${(c.properties ?? []).map((p) => p.label).join(", ") || "—"} |\n`;
  md += "\n";
}
writeFileSync(new URL("../../../docs/architecture/CATALOG.md", import.meta.url), md);
console.log(`catalog doc written (${APPLIANCE_CLASSES.length} appliances)`);
